# =============================================================================
# Phase 4 | Ripley's Cross-K Function: FP-to-WBC Spatial Attraction
#
# Tests whether FP predictions are spatially attracted to WBC locations at
# specific length scales (pixel radii) using the Cross-K function (K12):
#
#   K12(r) = expected number of FP centers within radius r of a WBC center,
#            normalized by the overall FP density
#
# Interpretation:
#   K12(r) > CSR envelope at radius r → FPs cluster around WBCs at scale r
#   K12(r) inside CSR envelope        → FP-WBC association not stronger than random
#
# The CSR (Complete Spatial Randomness) null envelope is generated by Monte
# Carlo simulation: randomly relocate FP centers 199 times within each image
# boundary and compute K12 for each permutation to build the 95% CI band.
#
# Paper reference: Molina et al. (2010), PMC2889688
# Implementation: pointpats (PySAL), install: pip install pointpats libpysal
#
# Outputs (saved to outputs/analysis_results/phase_4/):
#   ripley_cross_k_pooled_results.csv
#   ripley_cross_k_function_plot.png
# =============================================================================

import sys
from pathlib import Path

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from scipy.spatial import cKDTree

# =============================================================================
# PATHS
# =============================================================================
project_root  = Path("/home/sadeniji/scratch/Practicum_Main_Project")
phase3_dir    = project_root / "outputs/analysis_results/phase_3"
out_dir       = project_root / "outputs/analysis_results/phase_4"
out_dir.mkdir(parents=True, exist_ok=True)

pred_csv_b    = phase3_dir / "predictions_tp_fp_labeled_model_b.csv"
test_labels_b = project_root / "model_b/test/labels"

if not pred_csv_b.exists():
    sys.exit("ERROR: Run Phase 3 extract_predictions_and_label_tp_fp.py first.")

IMG_W, IMG_H  = 1024, 1024
CONF_THRESH   = 0.25
N_SIM         = 199     # Monte Carlo permutations for CSR envelope
RADII         = np.arange(10, 310, 10)   # 10px to 300px in 10px steps

# =============================================================================
# LOAD DATA
# =============================================================================
def load_wbc_gt(labels_dir):
    rows = []
    for lf in sorted(Path(labels_dir).glob("*.txt")):
        for line in lf.read_text().strip().split('\n'):
            parts = line.strip().split()
            if len(parts) < 5 or int(parts[0]) != 1:
                continue
            rows.append({'image_id': lf.stem,
                         'x': float(parts[1])*IMG_W,
                         'y': float(parts[2])*IMG_H})
    return pd.DataFrame(rows)


df_b   = pd.read_csv(pred_csv_b)
df_b   = df_b[df_b['conf'] >= CONF_THRESH].copy()
df_wbc = load_wbc_gt(test_labels_b)

fps = df_b[df_b['is_fp']].copy()
print(f"FP predictions: {len(fps)} across {fps['image_id'].nunique()} images")
print(f"WBC GT centers: {len(df_wbc)} across {df_wbc['image_id'].nunique()} images")

# =============================================================================
# CROSS-K FUNCTION (K12) PER IMAGE
# =============================================================================
def cross_k_one_image(fp_pts, wbc_pts, radii, area):
    """
    Compute K12(r) for one image.
    fp_pts: (N, 2) array of FP centers
    wbc_pts: (M, 2) array of WBC centers
    Returns: array of K12(r) values, one per radius in radii
    """
    if len(fp_pts) == 0 or len(wbc_pts) == 0:
        return np.full(len(radii), np.nan)

    lambda_fp = len(fp_pts) / area   # FP density
    tree = cKDTree(fp_pts)
    k_vals = []
    for r in radii:
        # For each WBC, count FPs within radius r
        counts = tree.query_ball_point(wbc_pts, r=r, return_length=True)
        k12 = np.sum(counts) / (len(wbc_pts) * lambda_fp)
        k_vals.append(k12)
    return np.array(k_vals)


def simulate_csr(fp_pts, wbc_pts, radii, area, n_sim, rng):
    """Generate CSR null distribution by randomly relocating FP centers."""
    sim_k = []
    for _ in range(n_sim):
        fp_rand = rng.uniform([0, 0], [IMG_W, IMG_H], size=(len(fp_pts), 2))
        sim_k.append(cross_k_one_image(fp_rand, wbc_pts, radii, area))
    return np.array(sim_k)   # shape (n_sim, len(radii))


rng    = np.random.default_rng(seed=42)
area   = IMG_W * IMG_H
k_observed_all = []
k_sim_all      = []

shared_images = set(fps['image_id'].unique()) & set(df_wbc['image_id'].unique())
print(f"\nImages with both FPs and WBC annotations: {len(shared_images)}")
print(f"Running Cross-K analysis (N_SIM={N_SIM}) — this may take a few minutes...")

for img_id in sorted(shared_images):
    fp_pts  = fps[fps['image_id'] == img_id][['x_ctr', 'y_ctr']].values
    wbc_pts = df_wbc[df_wbc['image_id'] == img_id][['x', 'y']].values

    if len(fp_pts) < 2 or len(wbc_pts) < 1:
        continue

    k_obs = cross_k_one_image(fp_pts, wbc_pts, RADII, area)
    k_sim = simulate_csr(fp_pts, wbc_pts, RADII, area, N_SIM, rng)

    k_observed_all.append(k_obs)
    k_sim_all.append(k_sim)

k_observed_all = np.array(k_observed_all)    # (n_images, n_radii)
k_sim_all      = np.array(k_sim_all)         # (n_images, n_sim, n_radii)

# Pool across images (mean K12 at each radius)
k_obs_mean     = np.nanmean(k_observed_all, axis=0)
k_sim_pooled   = k_sim_all.mean(axis=0)           # (n_sim, n_radii)
k_sim_lo       = np.percentile(k_sim_pooled, 2.5,  axis=0)
k_sim_hi       = np.percentile(k_sim_pooled, 97.5, axis=0)
k_csr_mean     = k_sim_pooled.mean(axis=0)         # theoretical expectation ≈ πr²

# =============================================================================
# SAVE RESULTS
# =============================================================================
df_k = pd.DataFrame({
    'radius_px': RADII,
    'K12_observed': k_obs_mean,
    'K12_csr_mean': k_csr_mean,
    'K12_csr_lo_2.5': k_sim_lo,
    'K12_csr_hi_97.5': k_sim_hi,
    'above_csr': k_obs_mean > k_sim_hi,
})
df_k.to_csv(out_dir / "ripley_cross_k_pooled_results.csv", index=False)
print(f"\nResults saved. Radii where K12 > CSR upper envelope:")
print(df_k[df_k['above_csr']][['radius_px', 'K12_observed', 'K12_csr_hi_97.5']].to_string(index=False))

# =============================================================================
# PLOT K12 VS CSR ENVELOPE
# =============================================================================
fig, axes = plt.subplots(1, 2, figsize=(14, 5))

# Panel 1: Raw K12
ax = axes[0]
ax.fill_between(RADII, k_sim_lo, k_sim_hi, alpha=0.3, color='grey', label='CSR 95% envelope')
ax.plot(RADII, k_csr_mean,  'k--',  linewidth=1.5, label='CSR mean')
ax.plot(RADII, k_obs_mean,  'r-',   linewidth=2,   label='Observed K12')
ax.set_title("Ripley's Cross-K: FP ↔ WBC (pooled over test images)")
ax.set_xlabel('Radius r (pixels)'); ax.set_ylabel('K12(r)')
ax.legend(); ax.grid(True, alpha=0.3)

# Panel 2: L12 transformation (Besag's L minus r, should = 0 under CSR)
csr_null = np.pi * RADII**2
l_obs  = np.sqrt(k_obs_mean  / np.pi) - RADII
l_lo   = np.sqrt(k_sim_lo    / np.pi) - RADII
l_hi   = np.sqrt(k_sim_hi    / np.pi) - RADII

ax = axes[1]
ax.fill_between(RADII, l_lo, l_hi, alpha=0.3, color='grey', label='CSR 95% envelope')
ax.axhline(0, color='k', linestyle='--', linewidth=1.5, label='CSR null (L-r=0)')
ax.plot(RADII, l_obs, 'r-', linewidth=2, label="Observed L12(r)−r")
ax.set_title("Besag's L12 − r  (positive = clustering above CSR)")
ax.set_xlabel('Radius r (pixels)'); ax.set_ylabel('L12(r) − r')
ax.legend(); ax.grid(True, alpha=0.3)

plt.tight_layout()
plt.savefig(out_dir / "ripley_cross_k_function_plot.png", dpi=150, bbox_inches='tight')
print(f"\nRipley's Cross-K plot saved to: {out_dir}/ripley_cross_k_function_plot.png")

print("\nPhase 4 — Ripley's Cross-K analysis complete.")
